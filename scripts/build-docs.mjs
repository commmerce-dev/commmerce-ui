// Copies built packages into docs/vendor so the docs site is static and self-contained.
import { cpSync, mkdirSync, rmSync, readFileSync, writeFileSync } from 'node:fs';
// Fail the build if the docs content has a syntax error or a component entry is missing a field.
const { components } = await import('../docs/content.js');
for (const c of components) for (const k of ['slug', 'tag', 'name', 'group', 'summary']) {
  if (typeof c[k] !== 'string' || !c[k]) throw new Error(`docs/content.js: ${c.slug ?? '?'} has no ${k}`);
}
const v = 'docs/vendor';
rmSync(v, { recursive: true, force: true });
mkdirSync(v, { recursive: true });
const copy = (from, to) => cpSync(from, `${v}/${to}`, { recursive: true });
copy('packages/tokens/dist/tokens.css', 'tokens.css');
copy('packages/tokens/dist/fonts.css', 'fonts.css');
copy('packages/tokens/dist/fonts', 'fonts'); // self-hosted Poppins: fonts.css points at fonts/*.woff2
copy('packages/tokens/dist/tokens.json', 'tokens.json');
copy('packages/ui/dist/cdn.js', 'cdn.js');
copy('packages/ui/dist/custom-elements.json', 'custom-elements.json');
copy('packages/app-bridge/dist/app-bridge.js', 'app-bridge.js');
copy('LICENSE.md', 'LICENSE.txt'); // .txt so the server shows it instead of downloading it
copy('THIRD_PARTY_NOTICES.txt', 'THIRD_PARTY_NOTICES.txt');
copy('packages/icons/dist/index.js', 'icons/index.js');
copy('packages/icons/dist/svg', 'icons/svg');
// The app starter, so developers outside this (private) repo can download it from the docs.
for (const f of ['README.md', 'package.json', 'server.mjs', 'fetch-vendor.mjs', 'dev-admin.html', 'public/index.html', 'test/server.test.mjs', 'test/pattern.test.mjs', '.gitignore']) {
  copy(`examples/app-starter/${f}`, `app-starter/${f}`);
}
// The React starter: source files only (no node_modules/ or dist/). package-lock.json keeps `npm ci` reproducible.
for (const f of ['README.md', 'package.json', 'package-lock.json', 'index.html', 'vite.config.mjs', 'playwright.config.js', '.gitignore',
  'src/main.jsx', 'src/App.jsx', 'src/ProductPanel.jsx', 'src/notify.js', 'src/data.js', 'src/app.css', 'tests/app.spec.js']) {
  copy(`examples/react-starter/${f}`, `react-starter/${f}`);
}
// The Vue, Angular, Svelte and Next.js starters, the same way. docs/starters.js lists their files (the docs link them).
const { FRAMEWORK_STARTERS } = await import('../docs/starters.js');
for (const s of FRAMEWORK_STARTERS) for (const [f] of s.files) copy(`examples/${s.dir}/${f}`, `${s.dir}/${f}`);
for (const f of ['README.md', 'index.php', 'lib/SessionToken.php', 'public/index.html', 'public/dev-admin.html', 'fetch-vendor.php', 'tests/run.php', '.htaccess', '.gitignore']) {
  copy(`examples/app-starter-php/${f}`, `app-starter-php/${f}`);
}
// One version for every published package, and the newest release note must be for that version.
// This is what keeps the hosted build's /v/<version>/ addresses moving forward with each release.
const pkgs = ['tokens', 'icons', 'ui', 'ui-react', 'app-bridge', 'review'].map((n) => JSON.parse(readFileSync(`packages/${n}/package.json`, 'utf8')));
const VERSION = pkgs[0].version;
const mismatch = pkgs.filter((p) => p.version !== VERSION).map((p) => `${p.name}@${p.version}`);
if (mismatch.length) throw new Error(`docs: package versions differ from ${VERSION}: ${mismatch.join(', ')}`);
// The Flutter package shares the number (compatibility policy).
const flutterVersion = readFileSync('flutter/commmerce_ui/pubspec.yaml', 'utf8').match(/^version:\s*(\S+)/m)?.[1];
if (flutterVersion !== VERSION) throw new Error(`docs: flutter/commmerce_ui/pubspec.yaml is ${flutterVersion}, packages are ${VERSION}. Set the same version.`);
// Heading ids are the version with dots as dashes: v0-9-0, v1-0-0-rc-1.
const topId = readFileSync('docs/releases.js', 'utf8').match(/<h2 id="v(\d[\w-]*)"/)?.[1];
const top = topId?.replace(/-/g, '.');
if (topId !== VERSION.replace(/\./g, '-')) throw new Error(`docs: newest release note is v${top} but packages are ${VERSION}. Add a release note (docs/releases.js) or bump the versions.`);
writeFileSync(`${v}/version.js`, `// generated by scripts/build-docs.mjs\nexport const VERSION = '${VERSION}';\n`);

// docs/index.html is page content only: claude.ai adds the document skeleton when it is published.
// dev.html wraps it the same way for local testing (standards mode, same as hosted).
const body = readFileSync('docs/index.html', 'utf8');
writeFileSync('docs/dev.html', `<!doctype html>\n<html lang="en">\n<head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover"><meta name="robots" content="noindex">\n${body}\n</html>\n`);
console.log(`docs: v${VERSION}, vendor files copied, dev.html written`);
